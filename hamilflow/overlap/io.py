"""DeepH-format input/output for the two-centre overlap (layout of ``deepx_dock``'s FHI-aims conversion).

What the conversion (``deepx_dock.convert.fhi_aims.aims_to_deeph.PeriodicAimsDataTranslator``)
writes, and what this package reproduces:

* ``POSCAR``: lattice and Cartesian positions in Å, atoms stable-sorted by species, positions
  mapped to the central cell as FHI-aims does (``map_to_center_cell``: fractional coordinates
  in [-0.5, 0.5), after a -1e-8 shift). ``R`` below refers to these positions.
* ``info.json``: ``elements_orbital_map`` = l of every radial function, in FHI-aims'
  ``basis-indices.out`` order (not sorted); each shell holds ``m = -l..l``.
* ``overlap.h5``: ``atom_pairs`` rows ``(R1, R2, R3, i, j)``, one dense block per row
  (``chunk_shapes``, ``chunk_boundaries``, flat row-major ``entries``). The block is
  ``<phi_i(r - tau_i) | phi_j(r - tau_j - R . lattice)>``, i.e. the bond vector is
  ``tau_j + R . lattice - tau_i``. Both ``(R, i, j)`` and ``(-R, j, i)`` are stored, on-site
  ``(0, 0, 0, i, i)`` included. S is dimensionless.
* ``hamiltonian.h5``: same layout; for overlap-only data the entries are an all-zero dataset.
"""

from __future__ import annotations

import collections
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Self

import h5py
import numpy as np
from deepx_dock.CONSTANT import (
    DEEPX_HAMILTONIAN_FILENAME,
    DEEPX_INFO_FILENAME,
    DEEPX_OVERLAP_FILENAME,
    DEEPX_POSCAR_FILENAME,
)

from hamilflow.projection.io import create_zero_dataset

_ATOMIC_NUMBERS = {"H": 1, "B": 5, "C": 6, "N": 7, "O": 8, "Si": 14, "S": 16, "Mo": 42}


@dataclass(frozen=True)
class DeephStructure:
    """Lattice (3, 3) rows in Å, Cartesian positions (n, 3) in Å, element symbols."""

    lattice: np.ndarray
    positions: np.ndarray
    species: list[str]


def map_to_center_cell(positions: np.ndarray, lattice: np.ndarray, eps: float = 1e-8,
                       tolerance: float = 5e-7) -> np.ndarray:
    """FHI-aims ``map_to_center_cell``, as reproduced by deepx_dock's conversion: fractional
    coordinates ``frac - eps - nint(frac - eps) + eps``. Raises when one is within
    ``tolerance`` of +-0.5, where the mapping is ambiguous."""
    frac = np.asarray(positions, dtype=np.float64) @ np.linalg.inv(lattice)
    frac = frac - eps
    frac = frac - np.rint(frac)
    frac = frac + eps
    close = np.abs(np.abs(frac) - 0.5) < tolerance
    if np.any(close):
        raise ValueError(f"fractional coordinate(s) too close to +-0.5: {frac[close]}")
    return frac @ lattice


def read_poscar(path: Path | str) -> DeephStructure:
    """Read a DeepH ``POSCAR`` (Cartesian, scale 1, as written by the conversion)."""
    lines = Path(path).read_text().splitlines()
    scale = float(lines[1].split()[0])
    lattice = np.array([[float(x) for x in lines[i].split()[:3]] for i in (2, 3, 4)]) * scale
    symbols = lines[5].split()
    counts = [int(x) for x in lines[6].split()]
    mode = lines[7].strip().lower()
    n = sum(counts)
    coords = np.array([[float(x) for x in lines[8 + i].split()[:3]] for i in range(n)])
    if mode.startswith("d"):
        coords = coords @ lattice
    else:
        coords = coords * scale
    species = [s for s, c in zip(symbols, counts, strict=True) for _ in range(c)]
    return DeephStructure(lattice=lattice, positions=coords, species=species)


def write_poscar(path: Path | str, structure: DeephStructure) -> Path:
    """Write ``POSCAR`` in the conversion's format (species grouped in order of appearance)."""
    counts = collections.Counter(structure.species)
    lines = [
        "POSCAR generated by hamilflow.overlap \n",
        "1.0\n",
        *("  " + " ".join(map(str, row)) + "\n" for row in structure.lattice),
        " ".join(counts.keys()) + "\n",
        " ".join(map(str, counts.values())) + "\n",
        "Cartesian\n",
        *("  " + " ".join(f"{x:.16f}" for x in p) + "\n" for p in structure.positions),
    ]
    path = Path(path)
    path.write_text("".join(lines))
    return path


def prepare_structure(lattice: np.ndarray, positions: np.ndarray, species: list[str]) -> DeephStructure:
    """Structure as the conversion stores it: atoms stable-sorted by species symbol, positions
    mapped to the central cell."""
    order = np.argsort(np.array(species), kind="stable")
    lattice = np.asarray(lattice, dtype=np.float64)
    pos = map_to_center_cell(np.asarray(positions, dtype=np.float64), lattice)[order]
    return DeephStructure(lattice=lattice, positions=pos, species=[species[i] for i in order])


def read_info(path: Path | str) -> dict:
    with open(Path(path) / DEEPX_INFO_FILENAME, encoding="utf-8") as f:
        return json.load(f)


def write_info(out_dir: Path | str, structure: DeephStructure,
               elements_orbital_map: dict[str, list[int]]) -> Path:
    """``info.json`` with the conversion's keys. ``fermi_energy_eV`` is 0: there is no SCF."""
    n_orb = sum(sum(2 * l + 1 for l in elements_orbital_map[s]) for s in structure.species)
    info = {
        "atoms_quantity": len(structure.species),
        "occupation": int(sum(_ATOMIC_NUMBERS[s] for s in structure.species)),
        "orbits_quantity": int(n_orb),
        "orthogonal_basis": False,
        "spinful": False,
        "fermi_energy_eV": 0.0,
        "elements_orbital_map": {s: [int(v) for v in elements_orbital_map[s]]
                                 for s in dict.fromkeys(structure.species)},
    }
    path = Path(out_dir) / DEEPX_INFO_FILENAME
    with open(path, "w", encoding="utf-8") as f:
        json.dump(info, f)
    return path


def read_layout(path: Path | str) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """``(atom_pairs, chunk_boundaries, chunk_shapes)`` of a DeepH matrix file, as int64."""
    with h5py.File(path, "r") as f:
        return (
            np.asarray(f["atom_pairs"][:], dtype=np.int64),
            np.asarray(f["chunk_boundaries"][:], dtype=np.int64),
            np.asarray(f["chunk_shapes"][:], dtype=np.int64),
        )


def read_blocks(path: Path | str, pair_indices: np.ndarray) -> list[np.ndarray]:
    """Dense blocks of the given rows of ``atom_pairs`` (reads only those entries)."""
    _, bounds, shapes = read_layout(path)
    with h5py.File(path, "r") as f:
        ent = f["entries"]
        return [np.asarray(ent[bounds[k]:bounds[k + 1]]).reshape(shapes[k]) for k in pair_indices]


def pair_layout(atom_pairs: np.ndarray, n_orb_per_atom: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """``(chunk_shapes, chunk_boundaries)`` of dense blocks for ``atom_pairs``."""
    shapes = np.stack([n_orb_per_atom[atom_pairs[:, 3]], n_orb_per_atom[atom_pairs[:, 4]]], axis=1)
    bounds = np.zeros(len(atom_pairs) + 1, dtype=np.int64)
    np.cumsum(shapes[:, 0] * shapes[:, 1], out=bounds[1:])
    return shapes.astype(np.int64), bounds


class OverlapWriter:
    """Writes ``overlap.h5`` (and a zero ``hamiltonian.h5`` with the same layout) block range by
    block range, so the full set of entries never sits in memory."""

    def __init__(self, out_dir: Path | str, atom_pairs: np.ndarray, n_orb_per_atom: np.ndarray,
                 write_dummy_hamiltonian: bool = True):
        self.out_dir = Path(out_dir)
        self.out_dir.mkdir(parents=True, exist_ok=True)
        self.atom_pairs = np.asarray(atom_pairs, dtype=np.int64)
        self.shapes, self.bounds = pair_layout(self.atom_pairs, np.asarray(n_orb_per_atom))
        n_entries = int(self.bounds[-1])
        for name, zero in ((DEEPX_OVERLAP_FILENAME, False),
                           (DEEPX_HAMILTONIAN_FILENAME, True)):
            if zero and not write_dummy_hamiltonian:
                continue
            with h5py.File(self.out_dir / name, "w") as f:
                f.create_dataset("atom_pairs", data=self.atom_pairs.astype(np.int32))
                f.create_dataset("chunk_boundaries", data=self.bounds)
                f.create_dataset("chunk_shapes", data=self.shapes.astype(np.int32))
                if zero:
                    create_zero_dataset(f, "entries", (n_entries,), np.float64)
                else:
                    f.create_dataset("entries", shape=(n_entries,), dtype=np.float64)
        self._file = h5py.File(self.out_dir / DEEPX_OVERLAP_FILENAME, "r+")

    def write(self, p0: int, blocks: np.ndarray) -> None:
        """Write the blocks of pairs ``p0 .. p0 + len(blocks)``, all of the same shape."""
        p1 = p0 + len(blocks)
        self._file["entries"][self.bounds[p0]:self.bounds[p1]] = np.ascontiguousarray(blocks).reshape(-1)

    def close(self) -> None:
        self._file.close()

    def __enter__(self) -> Self:
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()


def deeph_paths(d: Path | str) -> dict[str, Path]:
    d = Path(d)
    return {
        "poscar": d / DEEPX_POSCAR_FILENAME,
        "info": d / DEEPX_INFO_FILENAME,
        "overlap": d / DEEPX_OVERLAP_FILENAME,
        "hamiltonian": d / DEEPX_HAMILTONIAN_FILENAME,
    }
